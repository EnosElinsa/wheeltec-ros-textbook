"""Record observer cameras during a fresh Gazebo mapping/navigation session.

Run inside the fixed wheeltec simulation container, whose overlay is sourced.
Example: python3 /work/presentation/record_gazebo_demonstration.py launch
  --output /work/results/presentation-mapping --database /work/results/presentation.db
  --mode mapping
Observer images and map messages are recorded separately from mission evidence.
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
import sys
import time
import xml.etree.ElementTree as ET


def add_observers(sdf_path):
    tree = ET.parse(sdf_path)
    world = tree.getroot().find("world")
    # Views stay inside the original walls; all collision/algorithm inputs stay
    # as generated by the fixed simulation package.
    for name, xyz, target, hfov in (
        ("overview", (-5.5, -4.5, 7.0), (-.7, .7, 0), 1.5),
        ("detail", (-4.1, -2.5, 3.3), (-2.0, .8, 0), 1.15),
    ):
        dx, dy, dz = (target[i] - xyz[i] for i in range(3))
        yaw = math.atan2(dy, dx)
        pitch = math.atan2(-dz, math.hypot(dx, dy))
        model = ET.SubElement(world, "model", name=f"observer_{name}")
        ET.SubElement(model, "static").text = "true"
        ET.SubElement(model, "pose").text = " ".join(map(str, (*xyz, 0, pitch, yaw)))
        link = ET.SubElement(model, "link", name="camera")
        sensor = ET.SubElement(link, "sensor", name=name, type="camera")
        ET.SubElement(sensor, "always_on").text = "true"
        ET.SubElement(sensor, "update_rate").text = "8"
        ET.SubElement(sensor, "topic").text = f"/presentation/{name}"
        camera = ET.SubElement(sensor, "camera")
        ET.SubElement(camera, "horizontal_fov").text = str(hfov)
        image = ET.SubElement(camera, "image")
        for tag, value in (("width", 960), ("height", 600), ("format", "R8G8B8")):
            ET.SubElement(image, tag).text = str(value)
        clip = ET.SubElement(camera, "clip")
        ET.SubElement(clip, "near").text = ".05"
        ET.SubElement(clip, "far").text = "30"
    tree.write(sdf_path, encoding="unicode")


def launch_session(args):
    import wheeltec_vision_sim.launching as composition
    from launch import LaunchDescription, LaunchService
    from launch.actions import EmitEvent, ExecuteProcess, RegisterEventHandler, TimerAction
    from launch.event_handlers import OnProcessExit
    from launch.events import Shutdown
    from launch_ros.actions import Node

    out = Path(args.output).resolve()
    out.mkdir(parents=True, exist_ok=False)
    original = composition.write_model

    def model_with_observers(*a, **kw):
        sdf, urdf = original(*a, **kw)
        add_observers(sdf)
        return sdf, urdf

    composition.write_model = model_with_observers
    actions = composition.build(args.mode, "baseline", args.database, out / "launch")
    bridge = Node(package="ros_gz_bridge", executable="parameter_bridge",
                  name="observer_bridge", arguments=[
                      f"/presentation/{name}@sensor_msgs/msg/Image[ignition.msgs.Image"
                      for name in ("overview", "detail")])
    recorder = ExecuteProcess(cmd=[sys.executable, str(Path(__file__).resolve()), "record",
                                  "--output", str(out / "media")], output="screen")
    mission = ExecuteProcess(cmd=["ros2", "run", "wheeltec_vision_sim", "mission_runner", "run",
        "--output", str(out / "mission"), "--mode", args.mode, "--estimator", "baseline",
        "--scenario", "motion" if args.mode == "mapping" else "route", "--repeats", "3",
        "--launch-manifest", str(out / "launch/manifest.json"),
        "--ros-args", "-p", "use_sim_time:=true"], output="screen")

    def finished(event, context):
        (out / "mission-exit.json").write_text(json.dumps({"exit_code": event.returncode}) + "\n")
        return [EmitEvent(event=Shutdown(reason="presentation mission finished"))]

    service = LaunchService()
    service.include_launch_description(LaunchDescription([
        RegisterEventHandler(OnProcessExit(target_action=mission, on_exit=finished)),
        *actions, bridge, recorder, TimerAction(period=2., actions=[mission]),
        TimerAction(period=240., actions=[EmitEvent(event=Shutdown(reason="presentation deadline"))]),
    ]))
    return service.run()


def record(args):
    import cv2
    import numpy as np
    import rclpy
    from rclpy.node import Node
    from rclpy.qos import DurabilityPolicy, QoSProfile, ReliabilityPolicy, qos_profile_sensor_data
    from nav_msgs.msg import OccupancyGrid
    from sensor_msgs.msg import Image

    out = Path(args.output)
    out.mkdir(parents=True, exist_ok=False)
    for name in ("overview", "detail"):
        (out / name).mkdir()
    rclpy.init()
    node = Node("presentation_recorder")
    indices = {"overview": 0, "detail": 0}
    stream = (out / "frames.jsonl").open("w")

    def image_callback(msg, name):
        channels = {"rgb8": 3, "bgr8": 3, "rgba8": 4}.get(msg.encoding)
        if channels is None:
            raise ValueError(f"unsupported observer encoding {msg.encoding}")
        pixels = np.frombuffer(msg.data, dtype=np.uint8).reshape(msg.height, msg.step)
        pixels = pixels[:, :msg.width * channels].reshape(msg.height, msg.width, channels)
        if msg.encoding == "rgb8":
            pixels = cv2.cvtColor(pixels, cv2.COLOR_RGB2BGR)
        elif msg.encoding == "rgba8":
            pixels = cv2.cvtColor(pixels, cv2.COLOR_RGBA2BGR)
        relative = f"{name}/{indices[name]:05d}.jpg"
        cv2.imwrite(str(out / relative), pixels, [cv2.IMWRITE_JPEG_QUALITY, 94])
        stream.write(json.dumps(dict(view=name, file=relative,
            sim_ns=msg.header.stamp.sec * 10**9 + msg.header.stamp.nanosec,
            wall=time.monotonic())) + "\n")
        stream.flush()
        indices[name] += 1

    def map_callback(msg):
        record = dict(resolution=msg.info.resolution, width=msg.info.width, height=msg.info.height,
                      origin=dict(x=msg.info.origin.position.x, y=msg.info.origin.position.y),
                      frame=msg.header.frame_id, data=list(msg.data), wall=time.monotonic())
        (out / "map.json").write_text(json.dumps(record) + "\n")

    subscriptions = [node.create_subscription(Image, f"/presentation/{name}",
        lambda msg, name=name: image_callback(msg, name), qos_profile_sensor_data)
        for name in indices]
    map_qos = QoSProfile(depth=1, durability=DurabilityPolicy.TRANSIENT_LOCAL,
                         reliability=ReliabilityPolicy.RELIABLE)
    subscriptions.append(node.create_subscription(OccupancyGrid, "/map", map_callback, map_qos))
    try:
        rclpy.spin(node)
    except (KeyboardInterrupt, rclpy.executors.ExternalShutdownException):
        pass
    finally:
        stream.close()
        node.destroy_node()
        if rclpy.ok():
            rclpy.shutdown()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("launch", "record"))
    parser.add_argument("--output", required=True)
    parser.add_argument("--database")
    parser.add_argument("--mode", choices=("mapping", "localization"), default="mapping")
    options = parser.parse_args()
    if options.action == "launch":
        if not options.database:
            parser.error("--database is required for launch")
        raise SystemExit(launch_session(options))
    record(options)
